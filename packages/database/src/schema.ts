import { pgTable, text, timestamp, boolean, uuid, jsonb } from "drizzle-orm/pg-core";
import { user } from "./auth-schema";

// --- Business Tables ---

export const watchlists = pgTable("watchlists", {
	id: uuid("id").defaultRandom().primaryKey(),
	userId: text("userId").notNull().references(() => user.id),
	symbol: text("symbol").notNull(), // e.g. sh.600000
	name: text("name"), // optional custom name
	createdAt: timestamp("createdAt").defaultNow().notNull(),
	updatedAt: timestamp("updatedAt").defaultNow().notNull()
});

export const userConfigs = pgTable("user_configs", {
	id: uuid("id").defaultRandom().primaryKey(),
	userId: text("userId").notNull().references(() => user.id),
	key: text("key").notNull(), // e.g. "LLM_API_KEY", "LLM_MODEL_NAME"
	value: text("value").notNull(), // encrypted or plain depending on impl
	createdAt: timestamp("createdAt").defaultNow().notNull(),
	updatedAt: timestamp("updatedAt").defaultNow().notNull()
});

export const alphaTasks = pgTable("alpha_tasks", {
	id: uuid("id").defaultRandom().primaryKey(),
	userId: text("userId").notNull().references(() => user.id),
	status: text("status").notNull(), // "PENDING", "RUNNING", "COMPLETED", "FAILED"
	type: text("type").notNull(), // "FACTOR_MINING", "LLM_ANALYSIS"
	params: jsonb("params"), // JSON params for the task
	result: jsonb("result"), // JSON results
	createdAt: timestamp("createdAt").defaultNow().notNull(),
	updatedAt: timestamp("updatedAt").defaultNow().notNull()
});

export const alphaFactors = pgTable("alpha_factors", {
	id: uuid("id").defaultRandom().primaryKey(),
	userId: text("userId").notNull().references(() => user.id),
	name: text("name").notNull(),
	expression: text("expression").notNull(),
	hypothesis: text("hypothesis"),
	icValue: text("icValue"), // numeric value mapped to string/decimal to avoid precision issues
	icir: text("icir"),
	monotonicity: text("monotonicity"),
	direction: text("direction"), // 1 or -1
	isValid: boolean("isValid").default(false),
	generation: text("generation").default("0"),
	createdAt: timestamp("createdAt").defaultNow().notNull(),
	updatedAt: timestamp("updatedAt").defaultNow().notNull()
});

export const quantStrategies = pgTable("quant_strategies", {
	id: uuid("id").defaultRandom().primaryKey(),
	userId: text("userId").notNull().references(() => user.id),
	name: text("name").notNull(),
	style: text("style").notNull(), // e.g. "Momentum", "Value"
	factors: jsonb("factors").notNull(), // Array of factor IDs or configurations
	constraints: jsonb("constraints"), // e.g. max_drawdown limit
	reportMarkdown: text("reportMarkdown"), // Final output generated by writing-beats LLM
	performance: jsonb("performance"), // Backtest summary
	createdAt: timestamp("createdAt").defaultNow().notNull(),
	updatedAt: timestamp("updatedAt").defaultNow().notNull()
});
