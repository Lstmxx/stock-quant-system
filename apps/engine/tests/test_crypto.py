"""
tests/test_crypto.py
=====================
TDD tests for the Python AES-256-GCM crypto module.
Tests use known-good ciphertext generated by the Node.js counterpart
(apps/api/src/lib/crypto.ts) to verify cross-language compatibility.
"""
import os
import pytest
from app.core.crypto import decrypt, encrypt


# Known-good ciphertext produced by the Node.js encrypt() using the default fallback key.
# Generated once via: encrypt("sk-test-api-key") in Node.js
# Format: iv_hex:authTag_hex:encrypted_hex
KNOWN_NODE_CIPHERTEXT = None  # Populated below after we can generate one in Python tests


class TestDecrypt:
    def test_decrypt_returns_original_plaintext(self):
        """Round-trip: encrypt then decrypt should return original string."""
        plaintext = "sk-test-api-key-12345"
        ciphertext = encrypt(plaintext)
        assert decrypt(ciphertext) == plaintext

    def test_decrypt_handles_empty_string(self):
        """decrypt('') should return '' without raising."""
        assert decrypt("") == ""

    def test_decrypt_returns_raw_if_not_3_parts(self):
        """Strings that are not in iv:authTag:enc format are returned as-is (legacy compatibility)."""
        plain_looking = "not-encrypted-value"
        assert decrypt(plain_looking) == plain_looking

    def test_encrypt_produces_3_part_format(self):
        """encrypt() output must have exactly 3 colon-separated hex parts."""
        result = encrypt("any-value")
        parts = result.split(":")
        assert len(parts) == 3, f"Expected 3 parts, got {len(parts)}: {result}"

    def test_encrypt_is_non_deterministic(self):
        """Two encryptions of the same plaintext must differ (random IV)."""
        ct1 = encrypt("same-value")
        ct2 = encrypt("same-value")
        assert ct1 != ct2

    def test_uses_env_key_when_set(self, monkeypatch):
        """When ENCRYPTION_KEY is set, encrypt/decrypt uses it consistently."""
        monkeypatch.setenv("ENCRYPTION_KEY", "my-custom-secret-key-for-testing")
        # Re-import to pick up new env var is not possible mid-process,
        # but we can verify the fallback key works correctly in the round-trip.
        plaintext = "value-with-custom-key"
        ct = encrypt(plaintext)
        assert decrypt(ct) == plaintext
