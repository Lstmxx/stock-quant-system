export type ApiErrorName = Exclude<keyof typeof ApiCode, "SUCCESS">;
export type ApiErrorCode = (typeof ApiCode)[ApiErrorName];

export interface ApiSuccess<T> {
	success: true;
	code: typeof ApiCode.SUCCESS;
	message: string;
	data: T;
}

export interface ApiFailure {
	success: false;
	code: ApiErrorCode;
	message: string;
	data: null;
}

export type ApiResponse<T> = ApiSuccess<T> | ApiFailure;
